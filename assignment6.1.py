#matrics which i am going to perform operations on 
import numpy as np 

a=np.array=([[1,2,3],[4,5,6],[8,9,10]])
b=np.array=([[1,2,3],[4,5,6],[8,9,10]])


#add operation 

m=np.add(a,b) 
print("\n",m)
 
 
#differnece operation 

n=np.subtract(a,b)
print("\n",n)

#multiplication

o=np.multiply(a,b)
print("\n",o)

# dot operation 

p=np.dot(a,b)
print("\n",p)

#transpose 
q=np.transpose(a)
print("\n",q)



